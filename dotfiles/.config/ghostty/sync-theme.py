#!/usr/bin/env python3
"""Derive a Ghostty palette from the wallpaper, mirroring qs Theme.retheme()."""

import colorsys
import os
import signal
import subprocess
import sys

HOME = os.environ.get("HOME", os.path.expanduser("~"))
STATE = os.path.join(HOME, ".local/state/mist/wallpaper")
DEFAULT_WALL = os.path.join(HOME, ".config/wallpaper/THINK.png")
OUT = os.path.join(HOME, ".config/ghostty/theme")


def hsl(h, s, l):
    h = ((h % 360) + 360) % 360 / 360.0
    r, g, b = colorsys.hls_to_rgb(h, max(0.0, min(1.0, l)), max(0.0, min(1.0, s)))
    return (r, g, b)


def hexc(rgb):
    return "#" + "".join(f"{max(0, min(255, round(c * 255))):02x}" for c in rgb)


def mix_hue(h, toward, amount):
    diff = ((toward - h + 180) % 360) - 180
    return h + diff * amount


def analyze(path):
    raw = subprocess.check_output(
        [
            "sh",
            "-c",
            'ffmpeg -hide_banner -loglevel error -i "$1" '
            "-vf scale=16:9 -frames:v 1 -f rawvideo -pix_fmt rgb24 - "
            "| od -An -tu1 -v",
            "sh",
            path,
        ]
    )
    b = [int(x) for x in raw.split()]
    n = len(b) // 3
    if n < 4:
        return None

    tr = tg = tb = 0.0
    best_score = 0.0
    best = None
    for i in range(n):
        r, g, bl = (b[i * 3 + j] / 255.0 for j in range(3))
        tr += r
        tg += g
        tb += bl
        mx, mn = max(r, g, bl), min(r, g, bl)
        l = (mx + mn) / 2
        sat = 0.0
        h = 0.0
        if mx != mn:
            d = mx - mn
            sat = d / (2 - mx - mn) if l > 0.5 else d / (mx + mn)
            if mx == r:
                h = (g - bl) / d + (6 if g < bl else 0)
            elif mx == g:
                h = (bl - r) / d + 2
            else:
                h = (r - g) / d + 4
            h *= 60
        score = sat * (1 - abs(l - 0.5) * 1.4)
        if sat > 0.12 and score > best_score:
            best_score = score
            best = {"h": h, "s": sat}

    ar, ag, ab = tr / n, tg / n, tb / n
    amx, amn = max(ar, ag, ab), min(ar, ag, ab)
    al = (amx + amn) / 2
    ns = nh = 0.0
    if amx != amn:
        d = amx - amn
        ns = d / (2 - amx - amn) if al > 0.5 else d / (amx + amn)
        if amx == ar:
            nh = (ag - ab) / d + (6 if ag < ab else 0)
        elif amx == ag:
            nh = (ab - ar) / d + 2
        else:
            nh = (ar - ag) / d + 4
        nh *= 60

    return {
        "neutralH": best["h"] if best else nh,
        "neutralS": ns,
        "accentH": best["h"] if best else nh,
        "accentS": best["s"] if best else 0.0,
    }


def palette(p):
    nh = p["neutralH"]
    ns = max(0.0, min(0.30, p["neutralS"] * 0.9))
    ah = p["accentH"]
    a_s = max(0.0, min(0.85, p["accentS"] * 1.15))
    c = {
        "bg": hsl(nh, ns, 0.05),
        "surface": hsl(nh, ns, 0.10),
        "surfaceHigh": hsl(nh, ns, 0.16),
        "surfaceHighest": hsl(nh, ns, 0.22),
        "border": hsl(nh, ns * 0.9, 0.28),
        "borderHigh": hsl(ah, ns * 0.7 + a_s * 0.15, 0.48),
        "text": hsl(nh, ns * 0.7, 0.84),
        "textHigh": hsl(nh, ns * 0.5, 0.97),
        "textDim": hsl(ah, ns * 0.7 + a_s * 0.25, 0.60),
        "textMuted": hsl(nh, ns * 0.7, 0.38),
        "inverseBg": hsl(ah, min(a_s, 0.45), 0.86),
        "inverseText": hsl(nh, ns, 0.08),
        "accent": hsl(ah, a_s, 0.62),
        "accentDim": hsl(ah, a_s * 0.8, 0.40),
    }
    return c, nh, ns, ah, a_s


def ansi_palette(c, nh, ns, ah, a_s):
    tint = 0.10
    cap = 0.55

    def sem(hue, s, l):
        return hsl(mix_hue(hue, nh, tint), min(cap, s), l)

    normal = [
        c["bg"],
        sem(355, 0.50, 0.58),
        sem(145, 0.42, 0.55),
        sem(48, 0.52, 0.62),
        sem(ah, 0.35 + a_s * 0.40, 0.62),
        sem(ah + 30, 0.35 + a_s * 0.35, 0.64),
        sem(185, 0.38, 0.60),
        c["text"],
    ]
    bright = [
        c["textMuted"],
        sem(355, 0.55, 0.70),
        sem(145, 0.45, 0.67),
        sem(48, 0.55, 0.74),
        sem(ah, 0.45 + a_s * 0.35, 0.74),
        sem(ah + 30, 0.42 + a_s * 0.30, 0.76),
        sem(185, 0.42, 0.72),
        c["textHigh"],
    ]
    return normal + bright


def render(c, nh, ns, ah, a_s):
    ansi = ansi_palette(c, nh, ns, ah, a_s)
    # Match the quickshell bar: same tint as Theme.barBg (wallpaper hue, dark
    # tint, barTintSat ladder). Ghostty supplies the opacity/blur.
    gb_h = nh
    gb_s = max(0.18, min(0.42, ns * 0.8 + 0.14))
    gb_bg = hsl(gb_h, gb_s, 0.10)
    lines = [
        "# Generated by sync-theme.py - do not edit by hand.",
        "# Palette follows the current quickshell (mist) theme.",
        "",
        f"background = {hexc(gb_bg)}",
        f"foreground = {hexc(c['text'])}",
        f"cursor-color = {hexc(c['accent'])}",
        f"cursor-text = {hexc(c['bg'])}",
        f"selection-background = {hexc(c['borderHigh'])}",
        f"selection-foreground = {hexc(c['textHigh'])}",
        "",
    ]
    for i, rgb in enumerate(ansi):
        lines.append(f"palette = {i}={hexc(rgb)}")
    return "\n".join(lines) + "\n"


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else ""
    if not path:
        try:
            with open(STATE) as f:
                path = f.read().strip()
        except OSError:
            path = ""
    if not path or not os.path.exists(path):
        path = DEFAULT_WALL

    p = analyze(path) if os.path.exists(path) else None
    if p is None:
        p = {"neutralH": 0, "neutralS": 0, "accentH": 0, "accentS": 0}

    c, nh, ns, ah, a_s = palette(p)
    text = render(c, nh, ns, ah, a_s)

    try:
        with open(OUT) as f:
            old = f.read()
    except OSError:
        old = ""
    if text != old:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w") as f:
            f.write(text)
        # ask running ghostty instances to reload their config
        subprocess.run(["pkill", "-USR2", "-x", "ghostty"], check=False,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


if __name__ == "__main__":
    main()
